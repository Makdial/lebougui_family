window.I18N_DEFAULT = 'en';
window.I18N.current = window.I18N_DEFAULT;

window.t = function(key){
  const dict = window.I18N[window.I18N.current] || window.I18N.en;
  return (dict && dict[key] !== undefined) ? dict[key] : (window.I18N.en[key] || key);
};

window.applyI18n = function(){
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = window.t(key);
  });
  document.documentElement.lang = window.I18N.current;
  document.documentElement.setAttribute('data-lang', window.I18N.current);
};

window.setLang = function(lang){
  if(!window.I18N[lang]) return;
  window.I18N.current = lang;
  try { localStorage.setItem('as_lang', lang); } catch(e){}
  window.applyI18n();
  if (typeof window.renderGallery === 'function') window.renderGallery();
};

